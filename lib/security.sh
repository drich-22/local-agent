#!/usr/bin/env bash
# Shared security helpers for Local Agent scripts.
set -euo pipefail

LA_DATA_DIR="${LOCAL_AGENT_DATA:-${HOME}/.local/share/open-webui}"
LA_SECRETS_FILE="${LA_DATA_DIR}/secrets.env"
LA_RUNTIME_ENV="${LA_DATA_DIR}/local-agent.env"

load_repo_env() {
  local root="$1"
  if [[ -f "${root}/.env" ]]; then
    # shellcheck disable=SC1090
    set -a && source "${root}/.env" && set +a
  fi
}

validate_port() {
  local p="$1"
  [[ "$p" =~ ^[0-9]+$ ]] || return 1
  (( p >= 1024 && p <= 65535 ))
}

resolve_bind_host() {
  local bind="${BIND_HOST:-127.0.0.1}"
  if [[ "$bind" == "0.0.0.0" || "$bind" == "::" ]]; then
    if [[ "${ALLOW_LAN:-0}" != "1" ]]; then
      echo "ERROR: Binding to ${bind} requires ALLOW_LAN=1 (see docs/HARDENING.md)" >&2
      return 1
    fi
  fi
  echo "$bind"
}

ollama_origins_for_port() {
  local port="${1:-8080}"
  echo "http://127.0.0.1:${port},http://localhost:${port}"
}

ensure_secrets_file() {
  mkdir -p "${LA_DATA_DIR}"
  chmod 700 "${LA_DATA_DIR}" 2>/dev/null || true
  if [[ ! -f "${LA_SECRETS_FILE}" ]]; then
    local key
    if command -v openssl &>/dev/null; then
      key="$(openssl rand -hex 32)"
    else
      key="$(date +%s%N | shasum -a 256 | awk '{print $1}')"
    fi
    printf 'WEBUI_SECRET_KEY=%s\n' "$key" > "${LA_SECRETS_FILE}"
    chmod 600 "${LA_SECRETS_FILE}"
  fi
}

read_secret_key() {
  ensure_secrets_file
  # shellcheck disable=SC1090
  source "${LA_SECRETS_FILE}"
  if [[ -z "${WEBUI_SECRET_KEY:-}" ]]; then
    echo "ERROR: ${LA_SECRETS_FILE} missing WEBUI_SECRET_KEY" >&2
    return 1
  fi
  export WEBUI_SECRET_KEY
}

# Block accidental auth/signup weakening unless explicitly overridden.
assert_secure_runtime() {
  local auth signup
  auth="$(echo "${WEBUI_AUTH:-true}" | tr '[:upper:]' '[:lower:]')"
  signup="$(echo "${ENABLE_SIGNUP:-false}" | tr '[:upper:]' '[:lower:]')"

  if [[ "$auth" == "false" || "$auth" == "0" ]]; then
    if [[ "${ALLOW_INSECURE:-0}" != "1" ]]; then
      echo "ERROR: WEBUI_AUTH is disabled. Refusing to start (set ALLOW_INSECURE=1 to override)." >&2
      exit 1
    fi
    echo "WARNING: WEBUI_AUTH disabled with ALLOW_INSECURE=1" >&2
  fi

  if [[ "$signup" == "true" || "$signup" == "1" ]]; then
    if [[ "${ALLOW_SIGNUP:-0}" != "1" ]]; then
      echo "ERROR: ENABLE_SIGNUP is on. Use ALLOW_SIGNUP=1 only for first-admin bootstrap." >&2
      exit 1
    fi
    echo "WARNING: public signup enabled (bootstrap mode)" >&2
  fi

  if [[ -z "${WEBUI_SECRET_KEY:-}" ]]; then
    echo "ERROR: WEBUI_SECRET_KEY not set. Run ./harden.sh" >&2
    exit 1
  fi
}

write_hardened_runtime_env() {
  local port="${1:-8080}"
  read_secret_key
  cat > "${LA_RUNTIME_ENV}" <<EOF
# Generated by Local Agent — do not commit.
WEBUI_AUTH=true
ENABLE_SIGNUP=false
ENABLE_COMMUNITY_SHARING=false
ENABLE_MESSAGE_RATING=false
OLLAMA_BASE_URL=http://127.0.0.1:11434
WEBUI_SECRET_KEY=${WEBUI_SECRET_KEY}
AIOHTTP_CLIENT_SESSION_REDIRECT=false
# Restrict browser origins talking to Ollama (see OLLAMA_ORIGINS in LaunchAgent)
EOF
  chmod 600 "${LA_RUNTIME_ENV}"
}

export_runtime_env() {
  if [[ -f "${LA_RUNTIME_ENV}" ]]; then
    # shellcheck disable=SC1090
    set -a && source "${LA_RUNTIME_ENV}" && set +a
  fi
  export OLLAMA_BASE_URL="${OLLAMA_BASE_URL:-http://127.0.0.1:11434}"
  export WEBUI_AUTH="${WEBUI_AUTH:-true}"
  export ENABLE_SIGNUP="${ENABLE_SIGNUP:-false}"
  read_secret_key 2>/dev/null || true
}

check_path_permissions() {
  local mode
  mode="$(stat -f %Lp "${LA_SECRETS_FILE}" 2>/dev/null || stat -c %a "${LA_SECRETS_FILE}" 2>/dev/null || echo "")"
  [[ "$mode" == "600" ]] || [[ "$mode" == "400" ]] || {
    echo "WARNING: ${LA_SECRETS_FILE} should be mode 600 (is ${mode:-unknown})" >&2
    chmod 600 "${LA_SECRETS_FILE}" 2>/dev/null || true
  }
  chmod 700 "${LA_DATA_DIR}" 2>/dev/null || true
}
